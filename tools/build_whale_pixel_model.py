#!/usr/bin/env python3
"""Build a source-faithful, code-only pixel model from approved whale-maid sheets.

This is an authoring-time converter. It reads the approved local model sheets,
reduces them to an opaque pixel grid, then writes JavaScript run data. The
browser and MP4 renderer load *only the generated JS data* and issue Canvas
fillRect calls; no character image is fetched or composited at runtime.
"""
from __future__ import annotations

from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "standing": ROOT / "assets/cast/whale-maid/source/standing.png",
    "hands": ROOT / "assets/cast/whale-maid/source/hands.png",
    "laptop": ROOT / "assets/cast/whale-maid/source/laptop.png",
}
OUT = ROOT / "src/whale-pixel-model.js"
PIXEL_HEIGHT = 120
COLOURS = 48


def hex_colour(colour: tuple[int, int, int]) -> str:
    return "#%02x%02x%02x" % colour


def pixelate(path: Path) -> tuple[int, int, list[str], list[list[int]]]:
    source = Image.open(path).convert("RGBA")
    alpha = source.getchannel("A")
    bounds = alpha.getbbox()
    if not bounds:
        raise RuntimeError(f"No alpha silhouette in {path}")
    source = source.crop(bounds)
    target_w = round(source.width * PIXEL_HEIGHT / source.height)
    # Use a filtered reduction only during authoring so each final grid cell
    # represents the local source colour, then make it fully crisp/opaque.
    rgba = source.resize((target_w, PIXEL_HEIGHT), Image.Resampling.LANCZOS)
    alpha = rgba.getchannel("A")
    rgb = Image.new("RGB", rgba.size, (0, 0, 0))
    rgb.paste(rgba, mask=alpha)
    quant = rgb.quantize(colors=COLOURS, method=Image.Quantize.MEDIANCUT)
    palette = quant.getpalette()
    indices = list(quant.getdata())
    alpha_values = list(alpha.getdata())

    # Keep only source silhouette cells. Semi-transparent edge samples turn
    # into opaque artist-controlled pixel steps, not blurred compositor edges.
    used: dict[int, int] = {}
    for index, opacity in zip(indices, alpha_values):
        if opacity >= 72:
            used.setdefault(index, len(used))
    colour_table = []
    for old_index, _new_index in sorted(used.items(), key=lambda item: item[1]):
        base = old_index * 3
        colour_table.append(hex_colour(tuple(palette[base:base + 3])))

    # Runs are [y, x, length, paletteIndex]. Identical adjacent cells become
    # one Canvas rect; this remains a pixel drawing, never a bitmap drawImage.
    runs: list[list[int]] = []
    for y in range(PIXEL_HEIGHT):
        x = 0
        while x < target_w:
            p = y * target_w + x
            if alpha_values[p] < 72:
                x += 1
                continue
            old_index = indices[p]
            index = used[old_index]
            length = 1
            while x + length < target_w:
                next_p = y * target_w + x + length
                if alpha_values[next_p] < 72 or indices[next_p] != old_index:
                    break
                length += 1
            runs.append([y, x, length, index])
            x += length
    return target_w, PIXEL_HEIGHT, colour_table, runs


def js_value(value) -> str:
    if isinstance(value, str):
        return repr(value)
    if isinstance(value, list):
        return "[" + ",".join(js_value(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ",".join(f"{key}:{js_value(val)}" for key, val in value.items()) + "}"
    return str(value)


def main() -> None:
    models = {}
    for name, path in SOURCES.items():
        w, h, colours, runs = pixelate(path)
        models[name] = {"w": w, "h": h, "colours": colours, "runs": runs}
        print(f"{name}: {w}×{h}, {len(colours)} colours, {len(runs)} pixel runs")

    serialised = js_value(models)
    OUT.write_text(
        "/*\n"
        " * Generated by tools/build_whale_pixel_model.py from the approved local\n"
        " * whale-maid model sheets. This module intentionally contains only\n"
        " * source-derived pixel runs. Runtime never loads the source PNG files.\n"
        " */\n"
        "(function (root, factory) {\n"
        "  const model = factory();\n"
        "  if (typeof module === 'object' && module.exports) module.exports = model;\n"
        "  root.WHALE_PIXEL_MODEL = model;\n"
        "})(typeof globalThis !== 'undefined' ? globalThis : this, function () {\n"
        f"  return Object.freeze({serialised});\n"
        "});\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
